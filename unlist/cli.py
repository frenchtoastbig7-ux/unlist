"""Minimal command line: start the MCP server, run scheduled work, maintain the catalog.

The MCP connector is the real interface; this exists for launchd and for maintainers.
"""

from __future__ import annotations

from pathlib import Path

import click

from unlist import __version__, paths


@click.group()
@click.version_option(__version__, prog_name="unlist")
def main() -> None:
    """unlist: find and remove your own personal data from brokers and breaches. Local only."""


@main.command()
def status() -> None:
    """Counts, data directory, credentials present."""
    from unlist.mcp import tools

    click.echo(tools.status())


@main.command("serve-mcp")
def serve_mcp() -> None:
    """Run the MCP server over stdio (what the Claude desktop app launches)."""
    from unlist.mcp.server import main as serve

    serve()


@main.group()
def catalog() -> None:
    """Broker catalog maintenance."""


@catalog.command("validate")
def catalog_validate() -> None:
    """Load every shipped and override YAML file and report counts."""
    from unlist.catalog import load_catalog

    cat = load_catalog()
    origins = ", ".join(f"{k} {v}" for k, v in sorted(cat.by_origin().items()))
    categories = ", ".join(f"{k} {v}" for k, v in sorted(cat.by_category().items()))
    click.echo(f"{len(cat)} brokers: {origins}")
    click.echo(f"categories: {categories}")
    click.echo(f"searchable: {len(cat.searchable())}")


@catalog.command("import-registry")
@click.option(
    "--cppa",
    "cppa_csv",
    type=click.Path(exists=True, dir_okay=False, path_type=Path),
    required=True,
    help="registry.csv from cppa.ca.gov/data_broker_registry",
)
@click.option(
    "--markup",
    "markup_csv",
    type=click.Path(exists=True, dir_okay=False, path_type=Path),
    default=None,
    help="data-broker-opt-out-pages.csv from The Markup",
)
@click.option(
    "--out",
    "out_path",
    type=click.Path(dir_okay=False, path_type=Path),
    default=None,
    help="Default: the shipped registry/cppa.yaml",
)
def catalog_import_registry(
    cppa_csv: Path, markup_csv: Path | None, out_path: Path | None
) -> None:
    """Regenerate registry/cppa.yaml from the CPPA CSV (plus The Markup's opt-out pages)."""
    from unlist.catalog.importers import (
        build_registry,
        read_cppa,
        read_markup,
        write_registry_yaml,
    )
    from unlist.catalog.loader import REGISTRY_DIR

    rows = read_cppa(cppa_csv)
    markup = read_markup(markup_csv) if markup_csv else {}
    brokers = build_registry(rows, markup)
    out = out_path or REGISTRY_DIR / "cppa.yaml"
    header = (
        "# Generated by `unlist catalog import-registry`. Do not edit; curated entries in\n"
        "# brokers/*.yaml override these by id. Sources: California CPPA Data Broker Registry\n"
        "# (public record) and The Markup's opt-out pages dataset (Apache-2.0).\n"
        "# See CATALOG-SOURCES.md.\n"
    )
    write_registry_yaml(brokers, out, header)
    enriched = sum(1 for b in brokers if len(b.sources) > 1)
    click.echo(f"wrote {len(brokers)} brokers to {out}")
    click.echo(f"{enriched} enriched from The Markup opt-out pages dataset")


@main.command("password-check")
@click.option(
    "--label",
    prompt="Label (e.g. 'old bank password'; the password itself is never stored)",
)
@click.password_option(confirmation_prompt=False, help="Typed at a hidden prompt if omitted.")
def password_check(label: str, password: str) -> None:
    """Check a password against Pwned Passwords by k-anonymity. Only the first five
    characters of its SHA-1 leave this machine; only the label and count are kept."""
    from unlist.db import open_db
    from unlist.scanners.breaches.run import record_password_check

    count = record_password_check(open_db(), label, password)
    if count is None:
        raise click.ClickException("Pwned Passwords did not answer; try again later.")
    if count:
        click.echo(f"{label}: seen {count:,} times in breaches. Change it everywhere it is used.")
    else:
        click.echo(f"{label}: not found in Pwned Passwords.")


@main.command("form-assist")
@click.argument("request_id", type=int)
@click.option("--timeout", default=1800, show_default=True, help="Seconds to wait for you.")
@click.option("--headless", is_flag=True, hidden=True)
def form_assist(request_id: int, timeout: int, headless: bool) -> None:
    """Open a form request in a visible browser, prefill it, wait for you to finish."""
    from unlist.mcp.server import _load_dotenv
    from unlist.requests.form import run_form_assist

    _load_dotenv()
    click.echo(run_form_assist(request_id, timeout_s=timeout, headless=headless))


@main.command("inbox-poll")
def inbox_poll_cmd() -> None:
    """Read the opt-out mailbox and act on replies (same as the MCP tool)."""
    from unlist.mcp import tools
    from unlist.mcp.server import _load_dotenv

    _load_dotenv()
    click.echo(tools.inbox_poll())


@main.command("data-dir")
def data_dir_cmd() -> None:
    """Print the data directory."""
    click.echo(str(paths.data_dir()))


if __name__ == "__main__":
    main()
